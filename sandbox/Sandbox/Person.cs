using System.Security.Cryptography;

public class Person
{
    private string _name;

    private int _age;

    private bool _isLefthanded;

    private double _salary;

    public Person(string name, int age, bool isLefthanded, double salary)
    {
        name = _name;

        age = _age;

        isLefthanded = _isLefthanded;

        salary = _salary;
    }
}